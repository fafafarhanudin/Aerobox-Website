// Writes src/data/lite.ts: the counts and the handful of records the first screen shows,
// so the home page ships kilobytes instead of the whole library. Runs before every build.
// node scripts/lite-data.ts   (Node 23.6+ strips the types itself)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ICONS } from '../src/data/icons.ts'
import { UI_ICONS } from '../src/data/icons-ui.ts'
import { GRADIENTS } from '../src/data/gradients.ts'
import { AVATARS, FLAGS, PHOTOS } from '../src/data/collections.ts'
import { MARKS } from '../src/data/logos.ts'
import { LOCKUPS } from '../src/data/lockups.ts'
import { WORLD } from '../src/data/world.ts'
import { ISO } from '../src/data/iso.ts'

const src = new URL('../src/', import.meta.url).pathname
const home = readFileSync(join(src, 'pages/Home.tsx'), 'utf8')
const list = (name: string) => {
  const m = home.match(new RegExp(`const ${name} = \\[([^\\]]*)\\]`))
  if (!m) throw new Error(`Home.tsx: const ${name} not found`)
  return [...m[1].matchAll(/'([^']+)'/g)].map(x => x[1])
}

// interface glyphs: every plain-name string literal in the app source; any name built at runtime
// that is not caught here is still drawn, because ui.tsx fetches the full set on a miss
const files = (dir: string): string[] => readdirSync(dir).flatMap(f => {
  const p = join(dir, f)
  return statSync(p).isDirectory() ? (f === 'data' ? [] : files(p)) : /\.tsx?$/.test(f) ? [p] : []
})
const literals = new Set(files(src).flatMap(p => [...readFileSync(p, 'utf8').matchAll(/['"`]([a-z][a-z0-9-]*)['"`]/g)].map(m => m[1])))
const uiLite = UI_ICONS.filter(i => literals.has(i.name))

// library icons on the home bento: the wall plus the feature list of each card
const featIcons = [...home.matchAll(/\['([a-z0-9-]+)', '[A-Z]/g)].map(m => m[1])
const homeIconNames = new Set([...list('WALL'), ...featIcons])
const homeIcons = ICONS.filter(i => homeIconNames.has(i.name))

const brands = new Set(list('BRANDS')), reel = new Set(list('ISO_REEL'))
const out = {
  COUNTS: { icons: ICONS.length, gradients: GRADIENTS.length, avatars: AVATARS.length + PHOTOS.length, flags: FLAGS.length, marks: MARKS.length, lockups: LOCKUPS.length, world: WORLD.length, iso: ISO.length },
  UI_LITE: uiLite,
  HOME_ICONS: homeIcons,
  MARQUEE: MARKS.slice(0, 44).map(({ name, svg }) => ({ name, svg })),
  WORLD_LITE: WORLD.filter(w => brands.has(w.name)),
  ISO_LITE: ISO.filter(t => reel.has(t.key)),
}
const types: Record<string, string> = {
  COUNTS: 'Record<\'icons\' | \'gradients\' | \'avatars\' | \'flags\' | \'marks\' | \'lockups\' | \'world\' | \'iso\', number>',
  UI_LITE: 'Icon[]', HOME_ICONS: 'Icon[]', MARQUEE: '{ name: string; svg: string }[]', WORLD_LITE: 'World[]', ISO_LITE: '(typeof ISO)[number][]',
}
const body = Object.entries(out).map(([k, v]) => `export const ${k}: ${types[k]} = ${JSON.stringify(v)}`).join('\n')
writeFileSync(join(src, 'data/lite.ts'), `// Generated by scripts/lite-data.ts, do not edit. Rebuilt on every \`npm run build\`.
import type { Icon } from './icons-ui'
import type { World } from './world'
import type { ISO } from './iso'
${body}
`)
console.log(`lite.ts: ${uiLite.length}/${UI_ICONS.length} ui glyphs, ${homeIcons.length} home icons, ${out.WORLD_LITE.length} brands, ${out.ISO_LITE.length} iso`)
